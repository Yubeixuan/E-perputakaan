    private void cekDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cekDataActionPerformed
        try {
        Connection conn = koneksi.configDB();

        String sql =
        "SELECT p.id_pinjam, p.nip, b.judul_buku, b.jenis_buku, p.tgl_kembali " +
        "FROM pinjam p " +
        "JOIN buku b ON p.kode_buku = b.kode_buku " +
        "WHERE p.npm = ? AND p.kembali = 'n'";

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, txtnpm.getText());
        ResultSet rs = pst.executeQuery();

        if (!rs.next()) {
            JOptionPane.showMessageDialog(this, "Tidak ada pinjaman aktif");
            return;
        }

        // simpan id pinjam
        idPinjam = rs.getInt("id_pinjam");

        // tampilkan data
        txthasilnpm.setText(txtnpm.getText());
        txthasilnip.setText(rs.getString("nip"));
        txthasiljudulbuku.setText(rs.getString("judul_buku"));

        // factory jenis buku
        String jenisStr = rs.getString("jenis_buku");
        jenisBuku = JenisFactory.getJenis(jenisStr);

        if (jenisBuku == null) {
            JOptionPane.showMessageDialog(this, "Jenis buku tidak valid");
            return;
        }

        // hitung denda
        LocalDate deadline = rs.getDate("tgl_kembali").toLocalDate();
        LocalDate kembali = tgldikembalikan.getDate()
                .toInstant().atZone(ZoneId.systemDefault()).toLocalDate();

        long telat = ChronoUnit.DAYS.between(deadline, kembali);
        int denda = telat > 0 ? (int) telat * jenisBuku.getDendaPerHari() : 0;

        txthasildenda.setText(String.valueOf(denda));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_cekDataActionPerformed

